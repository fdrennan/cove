// The project starters (templates/starters/<id>/...), compiled into the server
// so every Cove - the on-prem one and the desktop builds - lays down the same
// files (host.rs create_domain). One table, generated here: (starter id, path
// inside the project, contents). A starter is a folder; adding one is adding a
// folder and a line in starters.rs, never a new include_str! list by hand.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    let mut entries: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
        // Build output and caches a starter's own trial run can leave behind.
        if ["target", "__pycache__", "node_modules", ".git", "out", "media"].contains(&name) {
            continue;
        }
        if p.is_dir() {
            println!("cargo:rerun-if-changed={}", p.display());
            walk(&p, out);
        } else {
            out.push(p);
        }
    }
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("templates/starters");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut files = Vec::new();
    walk(&root, &mut files);
    let mut src = String::from("/// (starter id, path in the project, contents) - generated by build.rs.\npub const STARTER_FILES: &[(&str, &str, &str)] = &[\n");
    for f in files {
        println!("cargo:rerun-if-changed={}", f.display());
        let rel = f.strip_prefix(&root).unwrap();
        let mut parts = rel.components();
        let id = parts.next().unwrap().as_os_str().to_string_lossy().into_owned();
        let path: PathBuf = parts.collect();
        if path.as_os_str().is_empty() {
            continue;
        }
        // Text only: a starter's pictures are drawn, not shipped.
        if std::fs::read_to_string(&f).is_err() {
            println!("cargo:warning=starter file is not UTF-8, left out: {}", f.display());
            continue;
        }
        // A starter's `gitignore` lands as `.gitignore` (a dotfile in the
        // template would hide it from the crate's own tooling).
        let path = path.to_string_lossy().replace('\\', "/");
        let path = if path == "gitignore" { ".gitignore".to_owned() } else { path };
        let _ = writeln!(src, "    ({id:?}, {path:?}, include_str!({:?})),", f.display().to_string());
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("starter_files.rs");
    std::fs::write(out, src).unwrap();
}
