//! Domains shared to work on, made true on this machine (operator,
//! 2026-11-02: "the ability for an end user to be able to help collaborate on
//! a site with me").
//!
//! The database says who may work on what: people_sharing.sql `share_editors`,
//! an accepted 'edit' share to a person or to a group they are in. This file
//! makes each row two things on disk, both root's, both undone when the row
//! goes:
//!
//!   - an ACL on the domain's folder in the platform checkout,
//!     `u:<them>:rwX` and its default, the same kind every owner has on their
//!     own folders;
//!   - a bind mount of that folder at `/home/<them>/shared/<host>`, as a
//!     systemd unit like the `~/domains` ones (ood-provision-user), so it
//!     comes back after a reboot.
//!
//! The unit file is the record: `granted` lists a person's shared domains
//! from the units alone (root-written, so a folder they made in ~/shared
//! themselves is not one), and `reconcile` compares the units with the
//! database and fixes the difference. `cove multiuser` runs it every 20 s
//! and right after a share changes.

use std::path::{Path, PathBuf};

use crate::host::PLATFORM_DOMAINS;

const UNITS: &str = "/etc/systemd/system";
/// The first line of every unit this file writes; nothing else is touched.
const MARK: &str = "# GENERATED by cove multiuser (src/shares.rs): a domain shared to work on.";

/// One row of share_access from 'read' up, as usernames: `user` may see (or,
/// from 'edit', work on) `owner`'s `host`.
#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
pub struct Grant {
    pub host: String,
    pub owner: String,
    pub user: String,
    /// people_sharing.sql's level: 'read' is a read-only mount and ACL.
    #[serde(default = "edit_role")]
    pub role: String,
}

fn edit_role() -> String {
    "edit".into()
}

impl Grant {
    fn read_only(&self) -> bool {
        self.role == "read"
    }
}

/// systemd's name for the mount unit at `path` (`systemd-escape --path`).
fn unit_name(path: &str) -> String {
    let p = path.trim_matches('/');
    let mut out = String::new();
    for (i, b) in p.bytes().enumerate() {
        match b {
            b'/' => out.push('-'),
            b'.' if i == 0 => out.push_str("\\x2e"),
            b if b.is_ascii_alphanumeric() || b == b'_' || b == b'.' || b == b':' => out.push(b as char),
            b => out.push_str(&format!("\\x{b:02x}")),
        }
    }
    out + ".mount"
}

fn mount_point(home: &Path, host: &str) -> PathBuf {
    home.join("shared").join(host)
}

fn unit_path(home: &Path, host: &str) -> PathBuf {
    Path::new(UNITS).join(unit_name(&mount_point(home, host).display().to_string()))
}

fn host_ok(h: &str) -> bool {
    h.contains('.') && !h.starts_with(['.', '-']) && h.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-')
}

// No After=local-fs.target: a local mount is already Before=local-fs.target by default, so
// that line made an ordering cycle and systemd dropped the mount at every boot (2026-11-27).
fn unit_body(g: &Grant, home: &Path) -> String {
    let src = Path::new(PLATFORM_DOMAINS).join(&g.owner).join(&g.host);
    let at = mount_point(home, &g.host);
    format!(
        "{MARK}\n# share: user={} owner={} host={} role={}\n[Unit]\nDescription={}'s {} shared with {} at {}\n\
         ConditionPathIsDirectory={}\n\n[Mount]\nWhat={}\nWhere={}\nType=none\nOptions={}\n\n[Install]\nWantedBy=multi-user.target\n",
        g.user,
        g.owner,
        g.host,
        g.role,
        g.owner,
        g.host,
        g.user,
        at.display(),
        src.display(),
        src.display(),
        at.display(),
        if g.read_only() { "bind,ro" } else { "bind" },
    )
}

/// The `# share:` line of a unit this file wrote: (user, owner, host).
fn parse(body: &str) -> Option<(String, String, String)> {
    if !body.starts_with(MARK) {
        return None;
    }
    let line = body.lines().find_map(|l| l.strip_prefix("# share: "))?;
    let get = |k: &str| line.split(' ').find_map(|kv| kv.strip_prefix(k)).map(str::to_owned);
    Some((get("user=")?, get("owner=")?, get("host=")?))
}

/// The domains shared with the person whose home is `home` to work on:
/// (host, path in their home, owner's username). Read from the units, so the
/// person's session (which cannot ask the database) and root agree.
pub fn granted(home: &Path) -> Vec<(String, String, String)> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(home.join("shared")).into_iter().flatten().flatten() {
        let host = e.file_name().to_string_lossy().into_owned();
        if !host_ok(&host) {
            continue;
        }
        let Ok(body) = std::fs::read_to_string(unit_path(home, &host)) else { continue };
        if let Some((_, owner, h)) = parse(&body) {
            if h == host {
                out.push((host, e.path().display().to_string(), owner));
            }
        }
    }
    out.sort();
    out
}

/// The level `host` is shared with the person whose home is `home` at, from
/// its unit ('edit' for units written before levels): Settings › Access lets a
/// 'manage' share set who may open it.
pub fn role_of(home: &Path, host: &str) -> Option<String> {
    let body = std::fs::read_to_string(unit_path(home, host)).ok()?;
    let (_, _, h) = parse(&body)?;
    if h != host {
        return None;
    }
    let line = body.lines().find_map(|l| l.strip_prefix("# share: "))?;
    Some(line.split(' ').find_map(|kv| kv.strip_prefix("role=")).unwrap_or("edit").to_owned())
}

/// The platform's own folder for a shared one: `/home/<u>/shared/<host>` →
/// `<PLATFORM_DOMAINS>/<owner>/<host>`, for anything run as the platform
/// account (which cannot enter /home/<u>, mode 750).
pub fn platform_path_of(home: &Path, host: &str) -> Option<PathBuf> {
    let body = std::fs::read_to_string(unit_path(home, host)).ok()?;
    let (_, owner, h) = parse(&body)?;
    (h == host).then(|| Path::new(PLATFORM_DOMAINS).join(owner).join(host))
}

/// share_access from 'read' up ('use' opens the app and needs no files), as
/// usernames, from the database.
fn wanted() -> Result<Vec<Grant>, String> {
    let out = crate::host::platform_psql_vars(
        "select coalesce(json_agg(json_build_object('host', e.domain, 'owner', o.username, 'user', u.username, 'role', e.role) order by e.domain, u.username), '[]'::json) \
           from share_access e \
           join ndexr_users o on lower(o.email) = e.owner_email and o.username <> '' \
           join ndexr_users u on lower(u.email) = e.email and u.username <> '' \
          where e.role in ('read', 'edit', 'manage')",
        &[],
    )?;
    serde_json::from_slice(String::from_utf8_lossy(&out).trim().as_bytes()).map_err(|e| format!("share_access: {e}"))
}

fn run(cmd: &str, args: &[&str]) -> Result<(), String> {
    let o = std::process::Command::new(cmd).args(args).output().map_err(|e| format!("{cmd}: {e}"))?;
    if o.status.success() {
        Ok(())
    } else {
        Err(format!("{cmd} {}: {}", args.join(" "), String::from_utf8_lossy(&o.stderr).trim()))
    }
}

fn mounted(at: &Path) -> bool {
    let at = at.display().to_string();
    std::fs::read_to_string("/proc/self/mountinfo").is_ok_and(|m| m.lines().any(|l| l.split(' ').nth(4) == Some(at.as_str())))
}

/// Give `g` on disk: ACL, mount point, unit, mounted. `uid`/`gid` and `home`
/// are the person's account.
fn grant(g: &Grant, home: &Path, uid: u32, gid: u32) -> Result<bool, String> {
    let src = Path::new(PLATFORM_DOMAINS).join(&g.owner).join(&g.host);
    if !src.is_dir() {
        return Err(format!("{} is not at {}", g.host, src.display()));
    }
    let unit = unit_path(home, &g.host);
    let body = unit_body(g, home);
    let at = mount_point(home, &g.host);
    let fresh = std::fs::read_to_string(&unit).ok().as_deref() != Some(body.as_str());
    if fresh {
        let perm = if g.read_only() { "r-X" } else { "rwX" };
        let who = format!("u:{0}:{perm},d:u:{0}:{perm}", g.user);
        run("setfacl", &["-R", "-m", &who, &src.display().to_string()])?;
        for d in [home.join("shared"), at.clone()] {
            if !d.is_dir() {
                std::fs::create_dir(&d).map_err(|e| format!("{}: {e}", d.display()))?;
                std::os::unix::fs::chown(&d, Some(uid), Some(gid)).map_err(|e| format!("{}: {e}", d.display()))?;
            }
        }
        std::fs::write(&unit, &body).map_err(|e| format!("{}: {e}", unit.display()))?;
        run("systemctl", &["daemon-reload"])?;
        run("systemctl", &["enable", unit.file_name().and_then(|n| n.to_str()).unwrap_or_default()])?;
    }
    if !mounted(&at) {
        run("systemctl", &["start", unit.file_name().and_then(|n| n.to_str()).unwrap_or_default()])?;
    } else if fresh {
        // A level changed while mounted: remount in place (a unit restart
        // unmounts, which fails while they have a file open).
        let opts = if g.read_only() { "remount,bind,ro" } else { "remount,bind,rw" };
        run("mount", &["-o", opts, &at.display().to_string()])?;
    }
    Ok(fresh)
}

/// Take back a unit this file wrote: unmount, remove the unit, the mount
/// point and the ACL.
fn revoke(unit: &Path, user: &str, owner: &str, host: &str) -> Result<(), String> {
    let name = unit.file_name().and_then(|n| n.to_str()).unwrap_or_default().to_owned();
    let body = std::fs::read_to_string(unit).unwrap_or_default();
    let at = body.lines().find_map(|l| l.strip_prefix("Where=")).map(PathBuf::from);
    let _ = run("systemctl", &["disable", "--now", &name]);
    std::fs::remove_file(unit).map_err(|e| format!("{}: {e}", unit.display()))?;
    run("systemctl", &["daemon-reload"])?;
    if let Some(at) = at.filter(|a| !mounted(a)) {
        let _ = std::fs::remove_dir(&at);
    }
    let src = Path::new(PLATFORM_DOMAINS).join(owner).join(host);
    if src.is_dir() {
        run("setfacl", &["-R", "-x", &format!("u:{user},d:u:{user}"), &src.display().to_string()])?;
    }
    Ok(())
}

/// Make the units match share_editors. `account` gives a username's
/// (home, uid, gid). Returns one line per change, for the audit log.
pub fn reconcile(account: impl Fn(&str) -> Option<(PathBuf, u32, u32)>) -> Result<Vec<String>, String> {
    static ONE: std::sync::Mutex<()> = std::sync::Mutex::new(());
    let _one = ONE.lock().unwrap_or_else(|e| e.into_inner());
    let want = wanted()?;
    let mut said = Vec::new();
    let mut keep: Vec<PathBuf> = Vec::new();
    for g in &want {
        if !host_ok(&g.host) || !crate::server::multiuser::valid_user(&g.user) || !crate::server::multiuser::valid_user(&g.owner) {
            continue;
        }
        let Some((home, uid, gid)) = account(&g.user) else { continue };
        keep.push(unit_path(&home, &g.host));
        match grant(g, &home, uid, gid) {
            Ok(true) => said.push(format!("{} may {} {}'s {}", g.user, if g.read_only() { "see" } else { "work on" }, g.owner, g.host)),
            Ok(false) => {}
            Err(e) => said.push(format!("{} on {}: {e}", g.user, g.host)),
        }
    }
    for e in std::fs::read_dir(UNITS).into_iter().flatten().flatten() {
        let p = e.path();
        if keep.contains(&p) || !p.extension().is_some_and(|x| x == "mount") {
            continue;
        }
        let Ok(body) = std::fs::read_to_string(&p) else { continue };
        let Some((user, owner, host)) = parse(&body) else { continue };
        match revoke(&p, &user, &owner, &host) {
            Ok(()) => said.push(format!("{user} no longer works on {owner}'s {host}")),
            Err(e) => said.push(format!("taking back {user} on {host}: {e}")),
        }
    }
    Ok(said)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_names_match_systemd_escape() {
        // `systemd-escape --path /home/robin/shared/garden.ndexr.io` and
        // `.../source-wars.ndexr.io`.
        assert_eq!(unit_name("/home/robin/shared/garden.ndexr.io"), "home-robin-shared-garden.ndexr.io.mount");
        assert_eq!(unit_name("/home/a/shared/source-wars.ndexr.io"), "home-a-shared-source\\x2dwars.ndexr.io.mount");
    }

    #[test]
    fn a_unit_says_whose_it_is() {
        let g = Grant { host: "garden.ndexr.io".into(), owner: "drennanfreddy".into(), user: "robin".into(), role: "edit".into() };
        let body = unit_body(&g, Path::new("/home/robin"));
        assert_eq!(parse(&body), Some(("robin".into(), "drennanfreddy".into(), "garden.ndexr.io".into())));
        assert!(body.contains("What=/home/ubuntu/ndexr/src/domains/drennanfreddy/garden.ndexr.io\n"));
        assert!(body.contains("Where=/home/robin/shared/garden.ndexr.io\n"));
        assert!(body.contains("Options=bind\n"));
        let ro = unit_body(&Grant { role: "read".into(), ..g.clone() }, Path::new("/home/robin"));
        assert!(ro.contains("Options=bind,ro\n"));
        assert_eq!(parse(&ro), parse(&body));
        // A unit someone else wrote is never ours to remove.
        assert_eq!(parse(&body.replacen(MARK, "# GENERATED by ndexr-user-provision", 1)), None);
    }
}
