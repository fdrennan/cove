#!/usr/bin/env bash
# Puts cove.ndexr.io on `cove multiuser` (every ndexr user, their own
# sessions) - idempotent. The proxy key is made once: root-only, read by the
# server and by nginx (whose master reads its config as root).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
sudo install -d -m 755 /etc/cove
if ! sudo test -s /etc/cove/proxy.key; then
  head -c 48 /dev/urandom | base64 | tr -d '/+=\n' | sudo tee /etc/cove/proxy.key >/dev/null
fi
sudo chmod 600 /etc/cove/proxy.key
key="$(sudo cat /etc/cove/proxy.key)"
printf '# GENERATED by cove.ndexr.io/onprem/install-multiuser.sh - the key nginx proves itself with.\nproxy_set_header X-Cove-Key "%s";\n' "$key" | sudo tee /etc/cove/nginx-proxy-key.conf >/dev/null
sudo chmod 600 /etc/cove/nginx-proxy-key.conf
# RStudio and Positron sessions (multiuser.conf rstudio-launcher,
# positron-launcher): run as every person, so
# root-owned and not writable by anyone else - multiuser refuses it otherwise.
sudo install -d -m 755 /usr/local/lib/cove
sudo install -m 755 -o root -g root "$here/rstudio-session.sh" /usr/local/lib/cove/rstudio-session
sudo install -m 755 -o root -g root "$here/positron-session.sh" /usr/local/lib/cove/positron-session
sudo install -m 644 "$here/cove-onprem-multiuser.service" /etc/systemd/system/cove-onprem-multiuser.service
sudo systemctl daemon-reload
sudo systemctl enable cove-onprem-multiuser >/dev/null 2>&1
echo "installed; onprem/run.sh restarts it after each build"
